package com.riscart.pixa.engine

/**
 * Los dibujos hechos a mano.
 *
 * Un nonograma generado al azar es un puzzle correcto, pero al terminarlo te
 * quedas con una mancha de píxeles. La gracia del género es que **el panel
 * terminado sea algo**: terminas y resulta que era un gato. Eso es lo que hace
 * que quieras el siguiente, y no hay forma de sacarlo de un generador.
 *
 * Cada dibujo pasa por el mismo filtro que los generados: en [CatalogoTest] se
 * comprueba que el solucionador lógico es capaz de terminarlo entero. Si un
 * dibujo necesitara adivinar, el test lo caza antes de que llegue al jugador.
 */
data class Dibujo(val nombre: String, val filas: List<String>) {
    val lado: Int get() = filas.size

    fun aPuzzle(): Puzzle {
        val lado = filas.size
        require(filas.all { it.length == lado }) { "«$nombre» no es cuadrado" }
        val solucion = filas.flatMap { fila -> fila.map { it == '#' } }
        return Puzzle(
            width = lado,
            height = lado,
            rowClues = rowCluesOf(solucion, lado, lado),
            colClues = colCluesOf(solucion, lado, lado),
            solution = solucion,
            nombre = nombre,
        )
    }
}

